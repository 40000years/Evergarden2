"""Build Advance Magic 1.34.1: repair the Bedrock pack that a stale rebuild bloated to 29 MB.

At 15:24 on 2026-10-26, a legendary-block/mushroom build wrote its assets into an old
advance-magic/dist pack, and that pack shipped in every JAR from then on. The stale pack
(2.33.1, below the 2.34.0 it replaced):
- brought back the effects retired in 1.29.0 (light sigil/halo/beacon, fire meteor, judge_left/right);
- dropped the judgment_gold particles;
- restored the flying staff tier 2 model from before 1.32.0;
- stored over 300 textures without palette compression.

This takes the 2.34.0 Bedrock pack from 1.32.1, adds only the legendary-block files that build
intended (regenerated by tools/legendary_block_assets.py with the same contents: entity, model,
animation, render controller, material, blocks.json, terrain_texture.json, legendary and mushroom
textures), and sets 2.35.0. Every other JAR entry stays byte-identical, including the Java pack,
the Geyser mappings, legendary-blocks.json and pack-mirror.properties.

    python tools/build_am_bedrock_repair_release.py [--base JAR] [--promote]

--promote also restores advance-magic/dist to the shipped packs, after saving the stale copies.
"""
import argparse
import hashlib
import io
import json
import os
import re
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'output/am-bedrock-repair-20261026'
GOOD = ROOT / 'dist/advance-magic-1.32.1-pack-log.jar'
VERSION = '1.34.1-bedrock-pack-repair'
BEDROCK_VERSION = [2, 35, 0]
DATE = (2026, 10, 26, 0, 0, 0)
INTENDED = re.compile(r'^(animations/legendary_block\.animation\.json|blocks\.json|entity/legendary_block\.entity\.json'
                      r'|materials/legendary_blocks\.material|models/entity/legendary_block\.geo\.json'
                      r'|render_controllers/legendary_block\.render\.json|textures/terrain_texture\.json'
                      r'|textures/blocks/[a-z_]+\.png|textures/legendary_blocks/[a-z_]+\.png)$')
PACKS = ('advance-magic-java.zip', 'advance-magic-bedrock.mcpack', 'geyser-mappings.json', 'pack-hashes.json')


def entries(data):
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        return {i.filename: archive.read(i) for i in archive.infolist() if not i.is_dir()}, archive.infolist()


def write_zip(files, infos):
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', zipfile.ZIP_DEFLATED) as out:
        done = set()
        for info in infos:
            if info.filename in files:
                item = zipfile.ZipInfo(info.filename, info.date_time)
                item.external_attr = info.external_attr
                out.writestr(item, files[info.filename], compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
                done.add(info.filename)
        for name in sorted(set(files) - done):
            out.writestr(zipfile.ZipInfo(name, DATE), files[name], compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
    return buffer.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--base', type=Path, default=ROOT / 'dist/advance-magic-1.34.0-pack-embedded.jar')
    parser.add_argument('--promote', action='store_true')
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    base = args.base.read_bytes()
    with zipfile.ZipFile(io.BytesIO(base)) as jar:
        stale_bytes = jar.read('resource-packs/advance-magic-bedrock.mcpack')
        hashes_raw = jar.read('resource-packs/pack-hashes.json')
        hashes = json.loads(hashes_raw)
        java_bytes = jar.read('resource-packs/advance-magic-java.zip')
        plugin = jar.read('plugin.yml').decode('utf8')
    with zipfile.ZipFile(GOOD) as jar:
        good_bytes = jar.read('resource-packs/advance-magic-bedrock.mcpack')
    good, good_infos = entries(good_bytes)
    stale, _ = entries(stale_bytes)
    if json.loads(good['manifest.json'])['header']['version'] != [2, 34, 0]:
        raise RuntimeError('Unexpected good pack version')
    taken = sorted(n for n in stale if INTENDED.match(n))
    if len(taken) < 40 or any(n.startswith('textures/particle/') for n in taken):
        raise RuntimeError('Unexpected legendary-block selection')
    files = dict(good)
    for name in taken:
        files[name] = stale[name]
    manifest = json.loads(files['manifest.json'])
    manifest['header']['version'] = BEDROCK_VERSION
    for module in manifest['modules']:
        module['version'] = BEDROCK_VERSION
    files['manifest.json'] = json.dumps(manifest, ensure_ascii=False, separators=(',', ':')).encode('utf8')
    repaired = write_zip(files, good_infos)
    # The stale build also recorded its own 30 MB Java pack here; record what the JAR really ships.
    hashes['advance-magic-bedrock.mcpack'] = hashlib.sha1(repaired).hexdigest()
    hashes['advance-magic-java.zip'] = hashlib.sha1(java_bytes).hexdigest()
    hashes_bytes = (json.dumps(hashes, indent=2) + ('\n' if hashes_raw.endswith(b'\n') else '')).encode()
    lines = plugin.splitlines(keepends=True)
    i = next(k for k, line in enumerate(lines) if line.startswith('version: '))
    lines[i] = f"version: '{VERSION}'" + lines[i][len(lines[i].rstrip('\r\n')):]
    replacements = {'plugin.yml': ''.join(lines).encode('utf8'), 'resource-packs/advance-magic-bedrock.mcpack': repaired,
                    'resource-packs/pack-hashes.json': hashes_bytes}
    jar_path = OUT / 'advance-magic.jar'
    with zipfile.ZipFile(io.BytesIO(base)) as previous, zipfile.ZipFile(jar_path, 'w', zipfile.ZIP_DEFLATED) as result:
        for info in previous.infolist():
            if info.filename in replacements:
                result.writestr(zipfile.ZipInfo(info.filename, DATE), replacements[info.filename],
                                compress_type=zipfile.ZIP_STORED if info.filename.endswith('.mcpack') else zipfile.ZIP_DEFLATED)
            else:
                result.writestr(info, previous.read(info))
    with zipfile.ZipFile(jar_path) as release, zipfile.ZipFile(io.BytesIO(base)) as previous:
        if release.testzip() is not None or release.namelist() != previous.namelist():
            raise RuntimeError('Invalid release archive')
        for info in previous.infolist():
            if info.filename not in replacements and release.read(info.filename) != previous.read(info):
                raise RuntimeError('Unrelated entry changed: ' + info.filename)
    report = {'version': VERSION, 'sha256': hashlib.sha256(jar_path.read_bytes()).hexdigest(), 'bedrock_version': BEDROCK_VERSION,
              'bedrock_bytes': {'stale': len(stale_bytes), 'repaired': len(repaired)}, 'legendary_block_files': taken,
              'retired_dropped': sorted(n for n in stale if n not in files), 'restored': sorted(n for n in good if n not in stale),
              'promoted': args.promote}
    if args.promote:
        dist = ROOT / 'advance-magic/dist'
        saved = OUT / 'stale-advance-magic-dist'
        saved.mkdir(exist_ok=True)
        with zipfile.ZipFile(jar_path) as release:
            for name in PACKS:
                if (dist / name).exists() and not (saved / name).exists():
                    shutil.copy2(dist / name, saved / name)
                staged = dist / (name + '.staged')
                staged.write_bytes(release.read('resource-packs/' + name))
                os.replace(staged, dist / name)
        source = ROOT / 'advance-magic/src/main/resources/plugin.yml'
        text = source.read_bytes().decode('utf8').splitlines(keepends=True)
        k = next(j for j, line in enumerate(text) if line.startswith('version: '))
        text[k] = f"version: '{VERSION}'" + text[k][len(text[k].rstrip('\r\n')):]
        source.write_bytes(''.join(text).encode('utf8'))
        for target in (ROOT / 'dist/advance-magic.jar', ROOT / 'dist' / f'advance-magic-{VERSION}.jar'):
            staged = target.with_suffix('.jar.staged')
            shutil.copy2(jar_path, staged)
            os.replace(staged, target)
    (OUT / 'release-build.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf8')
    print(json.dumps({k: report[k] for k in ('version', 'sha256', 'bedrock_version', 'bedrock_bytes', 'promoted')}, indent=2))
    print(len(taken), 'legendary-block files;', len(report['retired_dropped']), 'stale files dropped;', len(report['restored']), 'restored')


if __name__ == '__main__':
    main()
